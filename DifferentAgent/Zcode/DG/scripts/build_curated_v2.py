# 键 = manifest 中的 (folder, file)；不在 manifest 的 6 个文件用磁盘相对目录。
# 条目字段： t=txt 全长; j=接头[(pos_m, rel, note)] rel: eng/fld;
#            d=缺陷[(start_m, end_m, 类型原文, mechanism, weight, severity, note)];
#            n=notes_v2; link=同缆其他 fdr 文件(curated 键); po=按相覆盖; src=txt 文件名
# ---------------------------------------------------------------------------

def J(p, rel="eng", note="", flag=None):
    return {"pos_m": p, "rel": rel, "note": note, "flag": flag}


def D(s, e, t, m, w=1.0, sev=None, note="", flag=None):
    return {"start_m": s, "end_m": e, "type_raw": t, "mechanism": m,
            "weight": w, "severity": sev, "note": note, "flag": flag}


CURATED: dict[tuple[str, str], dict] = {}


def E(folder, file, t=None, j=(), d=(), n=(), link=(), po=None, src="其他信息.txt", folder_label=None):
    CURATED[(folder, file)] = dict(
        t=t, j=list(j), d=list(d), n=list(n), link=list(link), po=po, src=src,
        folder_label=folder_label)


